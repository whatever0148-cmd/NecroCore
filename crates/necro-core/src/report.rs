use crate::ir::Span;
use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum PathologyKind {
    /// Unreachable code.
    Ghost,
    /// Unbounded accumulator or buffer growth inside a loop.
    Vampire,
    /// A loop whose exit cannot depend on anything the loop changes.
    Zombie,
}

impl PathologyKind {
    pub fn label(self) -> &'static str {
        match self {
            PathologyKind::Ghost => "Ghost",
            PathologyKind::Vampire => "Vampire",
            PathologyKind::Zombie => "Zombie",
        }
    }
    pub fn technical(self) -> &'static str {
        match self {
            PathologyKind::Ghost => "unreachable code",
            PathologyKind::Vampire => "unbounded accumulator / buffer growth",
            PathologyKind::Zombie => "non-terminating loop",
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Pathology {
    pub kind: PathologyKind,
    pub label: String,
    pub block: String,
    pub span: Span,
    pub variable: Option<String>,
    /// Blocks that make up the loop, or the single unreachable block.
    pub blocks: Vec<String>,
    /// CFG edges (from, to) that explain the finding.
    pub cfg_edges: Vec<(String, String)>,
    pub detail: String,
    pub suggested_fix: String,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct NecroAutopsyReport {
    pub program: String,
    pub origin: String,
    pub block_count: usize,
    pub edge_count: usize,
    pub cfg_edges: Vec<(String, String)>,
    pub pathologies: Vec<Pathology>,
    /// Warnings produced by the front end (lifter) that are not CFG pathologies,
    /// such as two-digit year fields.
    pub lifter_warnings: Vec<String>,
    /// Auto-generated EARS requirements text for `.kiro/specs/`.
    pub requirements_markdown: String,
}

impl NecroAutopsyReport {
    pub fn count(&self, kind: PathologyKind) -> usize {
        self.pathologies.iter().filter(|p| p.kind == kind).count()
    }

    /// Renders the findings as an EARS requirements document.
    pub fn render_requirements(program: &str, origin: &str, paths: &[Pathology], warnings: &[String]) -> String {
        let mut s = String::new();
        s.push_str(&format!("# Requirements: resurrect `{program}` ({origin})\n\n"));
        s.push_str("Generated by necro-core from the static autopsy. Each requirement is written in EARS form so a Kiro spec can implement it.\n\n");
        if paths.is_empty() && warnings.is_empty() {
            s.push_str("## Requirement 1\n\nWHEN the lifted module is executed THE SYSTEM SHALL produce the same observable state as the reference interpreter for every input vector.\n");
            return s;
        }
        let mut n = 1;
        for p in paths {
            s.push_str(&format!("## Requirement {n}: {} in `{}` (line {})\n\n", p.label, p.block, p.span.line));
            s.push_str(&format!("User story: as a maintainer, I want the {} at bytes {}..{} healed so that the resurrected module behaves predictably.\n\n", p.kind.technical(), p.span.byte_start, p.span.byte_end));
            s.push_str("Acceptance criteria:\n\n");
            match p.kind {
                PathologyKind::Ghost => {
                    s.push_str(&format!("1. WHEN the lifter emits code for `{}` THE SYSTEM SHALL omit block `{}` because no CFG path from the entry reaches it.\n", program, p.block));
                    s.push_str("2. WHEN the healed module is compared with the reference interpreter THE SYSTEM SHALL report 100 percent parity, since removed code never executed.\n");
                }
                PathologyKind::Vampire => {
                    let v = p.variable.clone().unwrap_or_default();
                    s.push_str(&format!("1. WHEN the loop {} iterates THE SYSTEM SHALL bound `{}` by an explicit guard so that it cannot grow without limit.\n", p.blocks.join(", "), v));
                    s.push_str(&format!("2. IF `{}` reaches the guard limit THEN THE SYSTEM SHALL leave the loop and report the bound in the autopsy.\n", v));
                }
                PathologyKind::Zombie => {
                    s.push_str(&format!("1. WHEN the loop {} is entered THE SYSTEM SHALL decrement a fuel counter on every iteration and exit when it reaches zero.\n", p.blocks.join(", ")));
                    s.push_str("2. WHEN the differential prover runs the loop THE SYSTEM SHALL report the fuel exhaustion identically in the interpreter and the WebAssembly module.\n");
                }
            }
            s.push_str(&format!("\nDetail: {}\n\nSuggested fix: {}\n\n", p.detail, p.suggested_fix));
            n += 1;
        }
        for w in warnings {
            s.push_str(&format!("## Requirement {n}: front-end warning\n\nWHEN the program is lifted THE SYSTEM SHALL surface this warning in the autopsy: {w}\n\n"));
            n += 1;
        }
        s
    }
}
